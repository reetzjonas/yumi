// Regenerates packages/db/src/seed/bls-nutrition.ts from the BLS 4.0 data file.
// Download BLS_4_0_2025_DE.zip from https://blsdb.de ("Download BLS-Daten"), unzip it and run
//   bun run nutrition:bls path/to/BLS_4_0_Daten_2025_DE.xlsx
import { $ } from "bun";
import readXlsxFile from "read-excel-file/node";
import { BLS_CODES } from "../packages/db/src/seed/bls-codes";
import { nutritionValuesSchema } from "../packages/shared/src/nutrition";

const file = process.argv[2];
if (!file)
  throw new Error("Usage: bun run nutrition:bls <BLS_4_0_Daten_2025_DE.xlsx>");

// BLS component code -> our field. CHO is available carbohydrate, i.e. without fibre.
const COMPONENTS = {
  energyKcal: "ENERCC",
  proteinG: "PROT625",
  fatG: "FAT",
  carbsG: "CHO",
  sugarG: "SUGAR",
  fiberG: "FIBT",
  saltG: "NACL",
} as const;

const NEGLIGIBLE_WHEN_MISSING = ["proteinG", "fatG", "fiberG"];

const [header, ...rows] = await readXlsxFile(file);
if (!header) throw new Error("Empty BLS file");
const column = (code: string) => {
  const index = header.findIndex((cell) => String(cell).startsWith(`${code} `));
  if (index === -1) throw new Error(`BLS column ${code} not found`);
  return index;
};
const columns = Object.entries(COMPONENTS).map(
  ([field, code]) => [field, column(code)] as const,
);
const byCode = new Map(rows.map((row) => [String(row[0]), row]));

const round = (value: number) => Math.round(value * 100) / 100;
const problems: string[] = [];
const entries: string[] = [];
for (const code of [...new Set(Object.values(BLS_CODES))].sort()) {
  const row = byCode.get(code);
  if (!row) {
    problems.push(`${code}: not in the BLS file`);
    continue;
  }
  const values = Object.fromEntries(
    columns.map(([field, index]) => [field, row[index]]),
  );
  // BLS leaves negligible components empty (fibre in cheese, fat in wine); count those as 0.
  for (const field of NEGLIGIBLE_WHEN_MISSING)
    if (typeof values[field] !== "number") values[field] = 0;
  const missing = Object.entries(values).filter(
    ([, value]) => typeof value !== "number",
  );
  if (missing.length > 0) {
    problems.push(
      `${code} ${row[1]}: no ${missing.map(([f]) => f).join(", ")}`,
    );
    continue;
  }
  const parsed = nutritionValuesSchema.safeParse(
    Object.fromEntries(
      Object.entries(values).map(([field, value]) => [
        field,
        round(value as number),
      ]),
    ),
  );
  if (!parsed.success) {
    problems.push(`${code} ${row[1]}: ${parsed.error.message}`);
    continue;
  }
  entries.push(
    `  ${code}: { name: ${JSON.stringify(row[1])}, values: ${JSON.stringify(parsed.data)} },`,
  );
}
if (problems.length > 0)
  throw new Error(`BLS mapping problems:\n${problems.join("\n")}`);

const target = new URL(
  "../packages/db/src/seed/bls-nutrition.ts",
  import.meta.url,
);
await Bun.write(
  target,
  `// Generated by scripts/generate-bls-nutrition.ts — do not edit by hand.
// Source: Max Rubner-Institut (2025): Bundeslebensmittelschlüssel (BLS), Version 4.0 —
// Deutsche Nährstoffdatenbank. Karlsruhe. DOI: 10.25826/Data20251217-134202-0. License: CC BY 4.0.
// Per 100 g edible portion; carbsG = available carbohydrate (CHO), saltG = NACL.
// Protein, fat and fibre the BLS leaves empty count as 0.
import type { NutritionValues } from "@yumi/shared";

export const BLS_SOURCE = "BLS 4.0 (Max Rubner-Institut, CC BY 4.0)";

export const BLS_NUTRITION: Record<
  string,
  { readonly name: string; readonly values: NutritionValues }
> = {
${entries.join("\n")}
};
`,
);
await $`bun x biome format --write ${target.pathname}`.quiet();
console.log(`Wrote ${entries.length} BLS profiles`);
