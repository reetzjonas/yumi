import { mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { $ } from "bun";
import { z } from "zod";
import { PICTOGRAM_CATALOG } from "./pictogram-catalog";

// Pin source artwork and metadata so regeneration never silently changes style.
const revision = "1ffb34c752ecf5d402f04cfb4b392c77f57c54bc";
const upstream = `https://raw.githubusercontent.com/microsoft/fluentui-emoji/${revision}`;
const target = new URL("../apps/web/public/pictograms/", import.meta.url);
const metadataSchema = z.object({ glyph: z.string(), cldr: z.string() });
const treeSchema = z.object({
  tree: z.array(z.object({ path: z.string() })),
});

async function download(path: string) {
  const response = await fetch(`${upstream}/${path}`, {
    signal: AbortSignal.timeout(30_000),
  });
  if (!response.ok)
    throw new Error(`Fluent download failed: ${response.status} ${path}`);
  return response;
}

await mkdir(target, { recursive: true });
const license = await (await download("LICENSE")).text();
if (!license.includes("MIT License"))
  throw new Error("Fluent Emoji license changed; review before regenerating");
await Bun.write(new URL("LICENSE", target), license);

const treeResponse = await fetch(
  `https://api.github.com/repos/microsoft/fluentui-emoji/git/trees/${revision}?recursive=1`,
  { signal: AbortSignal.timeout(30_000) },
);
if (!treeResponse.ok)
  throw new Error(`Fluent tree request failed: ${treeResponse.status}`);
const { tree } = treeSchema.parse(await treeResponse.json());
const rows: {
  readonly emoji: string;
  readonly de: string;
  readonly en: string;
}[] = [];
for (const [de, name] of PICTOGRAM_CATALOG) {
  const folder = `assets/${name}/`;
  const svg = tree.find(
    ({ path }) => path.startsWith(`${folder}Flat/`) && path.endsWith(".svg"),
  );
  if (!svg) throw new Error(`Flat artwork missing: ${name}`);
  const metadata = metadataSchema.parse(
    await (await download(`${folder}metadata.json`)).json(),
  );
  const emoji = metadata.glyph;
  const file = Array.from(emoji.replaceAll("\uFE0F", ""))
    .map((point) => point.codePointAt(0)?.toString(16))
    .join("-");
  await Bun.write(new URL(`${file}.svg`, target), await download(svg.path));
  rows.push({ emoji, de, en: metadata.cldr });
}
const output = `// Generated by scripts/generate-pictograms.ts; edit scripts/pictogram-catalog.ts.
import { z } from "zod";

export const PICTOGRAMS = [
${rows.map(({ emoji, de, en }) => `  { emoji: ${JSON.stringify(emoji)}, de: ${JSON.stringify(de)}, en: ${JSON.stringify(en)} },`).join("\n")}
] as const;

export const PICTOGRAM_KEYS = PICTOGRAMS.map(({ emoji }) => emoji);
export const pictogramKeySchema = z.enum(PICTOGRAM_KEYS);
export type PictogramKey = (typeof PICTOGRAMS)[number]["emoji"];

const files = new Map<string, string>(
  PICTOGRAMS.map(({ emoji }) => {
    const normalized = emoji.replaceAll("\\uFE0F", "");
    const codepoints = Array.from(normalized)
      .map((point) => point.codePointAt(0)?.toString(16)).join("-");
    return [normalized, \`\${codepoints}.svg\`];
  }),
);

/** Resolve only bundled artwork; presentation selectors do not affect the key. */
export function pictogramFile(emoji: string | null | undefined): string | null {
  return emoji ? files.get(emoji.replaceAll("\\uFE0F", "")) ?? null : null;
}
`;
const sharedFile = new URL(
  "../packages/shared/src/pictograms.ts",
  import.meta.url,
);
await Bun.write(sharedFile, output);
await $`${process.execPath} x biome format --write ${fileURLToPath(sharedFile)}`;
console.log(
  `Generated ${rows.length} Fluent Emoji Flat SVGs in ${fileURLToPath(target)}`,
);
