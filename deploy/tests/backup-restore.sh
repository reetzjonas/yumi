#!/bin/sh
# Real PostgreSQL test. Only the uniquely named databases below are modified.
set -eu

ROOT=$(CDPATH= cd -- "$(dirname "$0")/../.." && pwd)
CONTAINER=${POSTGRES_CONTAINER:-yumi-postgres-1}
DB_USER=${POSTGRES_USER:-yumi}
DB_PASSWORD=${POSTGRES_PASSWORD:-yumi}
RUN_ID="$(date -u +%Y%m%d%H%M%S)_$$"
SOURCE="yumi_backup_source_$RUN_ID"
TARGET="yumi_backup_target_$RUN_ID"
WORK="/tmp/yumi-backup-$RUN_ID"

sql() {
  docker exec -i -e PGPASSWORD="$DB_PASSWORD" "$CONTAINER" \
    psql -X -h 127.0.0.1 -U "$DB_USER" -d "$1" -v ON_ERROR_STOP=1 -At
}

cleanup() {
  # These names are generated above, never supplied by the caller.
  printf 'DROP DATABASE IF EXISTS "%s"; DROP DATABASE IF EXISTS "%s";\n' "$SOURCE" "$TARGET" |
    sql postgres > /dev/null
  docker exec -u 1000:1000 "$CONTAINER" rm -rf "$WORK"
}
trap cleanup EXIT
trap 'exit 1' HUP INT TERM

printf 'CREATE DATABASE "%s"; CREATE DATABASE "%s";\n' "$SOURCE" "$TARGET" | sql postgres
sql "$SOURCE" <<'SQL'
CREATE TABLE households (id uuid PRIMARY KEY, name text NOT NULL);
CREATE TABLE recipes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  household_id uuid NOT NULL REFERENCES households(id),
  name text NOT NULL,
  metadata jsonb NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE shopping_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipe_id bigint NOT NULL REFERENCES recipes(id),
  quantity numeric(10,2) NOT NULL CHECK (quantity > 0),
  checked boolean NOT NULL DEFAULT false
);
INSERT INTO households VALUES ('00000000-0000-0000-0000-000000000036', 'Backup test');
INSERT INTO recipes (household_id, name, metadata) VALUES
  ('00000000-0000-0000-0000-000000000036', U&'Cr\00e8me soup', '{"servings":4,"tags":["vegetarian"]}'),
  ('00000000-0000-0000-0000-000000000036', 'Pasta', '{"servings":2}');
INSERT INTO shopping_items (recipe_id, quantity, checked) VALUES (1, 2.50, false), (2, 1.00, true);
SQL

fingerprint() {
  sql "$1" <<'SQL'
SELECT jsonb_build_object(
  'households', (SELECT jsonb_agg(to_jsonb(h) ORDER BY id) FROM households h),
  'recipes', (SELECT jsonb_agg(to_jsonb(r) ORDER BY id) FROM recipes r),
  'shopping_items', (SELECT jsonb_agg(to_jsonb(s) ORDER BY id) FROM shopping_items s)
)::text;
SQL
}
EXPECTED=$(fingerprint "$SOURCE")
docker exec -u 1000:1000 "$CONTAINER" mkdir "$WORK"
# Run the chart's exact script with the chart's unprivileged UID.
docker exec -i -u 1000:1000 -e BACKUP_DIR="$WORK" \
  -e DATABASE_URL="$SOURCE" -e PGHOST=127.0.0.1 -e PGUSER="$DB_USER" \
  -e PGPASSWORD="$DB_PASSWORD" "$CONTAINER" sh -s < "$ROOT/deploy/helm/yumi/files/backup.sh"
docker exec -u 1000:1000 "$CONTAINER" sh -c 'cd "$1" && sha256sum -c database.dump.sha256' sh "$WORK"

restore() {
  docker exec -i -u 1000:1000 -e DATABASE_URL="$TARGET" \
    -e PGHOST=127.0.0.1 -e PGUSER="$DB_USER" -e PGPASSWORD="$DB_PASSWORD" \
    "$CONTAINER" sh -s -- "$WORK/database.dump" < "$ROOT/scripts/backup/restore.sh"
}
restore
ACTUAL=$(fingerprint "$TARGET")
[ "$EXPECTED" = "$ACTUAL" ] || { echo "Restored data differs" >&2; exit 1; }
echo "PASS: UUID, Unicode, JSONB, timestamps, numeric and related rows round-trip"

NEXT_ID=$(sql "$TARGET" <<'SQL'
INSERT INTO recipes (household_id, name)
VALUES ('00000000-0000-0000-0000-000000000036', 'After restore') RETURNING id;
SQL
)
[ "$NEXT_ID" = "$(printf '3\nINSERT 0 1')" ] || { echo "Identity sequence did not advance" >&2; exit 1; }
if printf 'INSERT INTO shopping_items (recipe_id, quantity) VALUES (99999, 1);\n' |
  sql "$TARGET" > /dev/null 2>&1; then
  echo "Restored foreign key was not enforced" >&2
  exit 1
fi
echo "PASS: identity sequence and foreign-key enforcement"

# A conflict halfway through schema creation must roll back earlier DDL.
printf 'DROP DATABASE "%s"; CREATE DATABASE "%s";\n' "$TARGET" "$TARGET" | sql postgres
printf 'CREATE TABLE recipes (sentinel text); INSERT INTO recipes VALUES ('"'preserved'"');\n' | sql "$TARGET"
if restore; then
  echo "Restore unexpectedly succeeded against a conflicting table" >&2
  exit 1
fi
ROLLED_BACK=$(sql "$TARGET" <<'SQL'
SELECT to_regclass('public.households') IS NULL;
SELECT sentinel FROM recipes;
SQL
)
[ "$ROLLED_BACK" = "$(printf 't\npreserved')" ] || { echo "Restore was not atomic" >&2; exit 1; }
echo "PASS: conflicting restore fails and rolls back without changing existing data"
echo "PASS: real PostgreSQL dump/restore completed"
